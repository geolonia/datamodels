    context: 'あなたの @context', schema: 'JSON Schema（カタログの属性 + あなたの属性）', copy: 'コピー', copied: 'コピーしました',
    propose: 'この属性がカタログにあるべきなら、提案フォームで知らせてください（内容は入力済み）。',
    schemaNote: (v: string) => `カタログのスキーマは閉じている（additionalProperties: false）ため、参照だけでは属性を足せません。これは ${v} をもとに作ったもので、新しいバージョンに移るときは作り直してください。$id はあなたの URL に書き換えてください。`,
    problems: {
      prefix: '接頭辞は英小文字で始まる英小文字・数字・ハイフンにしてください（例 acme）。', prefixReserved: (n: string) => `接頭辞「${n}」は NGSI-LD で予約されています。`,
