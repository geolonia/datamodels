  catalog.data.mjs at build time. ?model=<subject>/<Type> preselects a model.
-->
<script setup lang="ts">
import { computed, onMounted, reactive, ref } from 'vue'
import { data } from './catalog.data.mjs'
import { buildExtension, proposalUrl } from '../../../scripts/lib/extend.mjs'

const props = defineProps<{ lang: 'ja' | 'en' }>()
const L = {
  ja: {
    model: 'モデル', prefix: '接頭辞', base: '名前空間（あなたの IRI）', attributes: 'あなたの属性', add: '属性を追加', remove: '削除',
