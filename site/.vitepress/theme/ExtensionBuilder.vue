          </optgroup>
        </select>
      </label>
      <label>{{ L.prefix }}<input v-model="form.prefix" spellcheck="false" autocapitalize="off" /></label>
      <label class="wide">{{ L.base }}<input v-model="form.base" spellcheck="false" autocapitalize="off" /></label>
    </div>

    <h3>{{ L.attributes }}</h3>
    <div class="attrs">
      <div v-for="(a, i) in form.attributes" :key="i" class="attr">
        <label>{{ L.name }}<input v-model="a.name" spellcheck="false" autocapitalize="off" /></label>
        <label>{{ L.ngsiType }}
          <select v-model="a.ngsiType"><option>Property</option><option>Relationship</option><option>GeoProperty</option></select>
        </label>
        <label v-if="a.ngsiType === 'Property'">{{ L.valueType }}
          <select v-model="a.valueType"><option v-for="v in ['string', 'number', 'integer', 'boolean', 'object', 'array']" :key="v">{{ v }}</option></select>
        </label>
        <label v-if="a.ngsiType === 'Property' && a.valueType === 'string'">{{ L.format }}
          <select v-model="a.format"><option value="">{{ L.none }}</option><option>date-time</option><option>date</option><option>uri</option></select>
        </label>
        <label class="check"><input v-model="a.required" type="checkbox" />{{ L.required }}</label>
        <label class="wide">{{ L.description }}<input v-model="a.description" /></label>
        <button type="button" class="remove" @click="form.attributes.splice(i, 1)">{{ L.remove }}</button>
      </div>
      <button type="button" class="add" @click="add">+ {{ L.add }}</button>
    </div>

    <div v-if="messages.length" class="problems" aria-live="polite"><ul><li v-for="(m, i) in messages" :key="i">{{ m }}</li></ul></div>
    <template v-else>
      <div class="out">
        <div class="head"><h3>{{ L.context }}</h3><button type="button" @click="copy('context')">{{ copied === 'context' ? L.copied : L.copy }}</button></div>
        <pre><code>{{ pretty(result.context) }}</code></pre>
      </div>
      <div class="out">
        <div class="head"><h3>{{ L.schema }}</h3><button type="button" @click="copy('schema')">{{ copied === 'schema' ? L.copied : L.copy }}</button></div>
        <p class="note">{{ L.schemaNote(model.schemaExact) }}</p>
        <pre class="long"><code>{{ pretty(result.schema) }}</code></pre>
      </div>
      <p><a :href="proposal" target="_blank" rel="noreferrer">{{ L.propose }}</a></p>
    </template>
  </div>
</template>

