      none: '属性を 1 つ以上入力してください。', name: (n: string) => `「${n}」: 属性名は英小文字で始まる英数字（camelCase）にしてください。`,
      inModel: (n: string) => `「${n}」はこのモデルに既にあります。そのまま使ってください（意味を変えてはいけません）。`,
      reserved: (n: string) => `「${n}」は NGSI-LD コアの予約語です。別の名前にしてください。`,
      inContext: (n: string) => `「${n}」はこのサブジェクトの @context で別の属性として定義済みです。同じ意味ならその属性を使い、違う意味なら別の名前にしてください。`,
      prefixInContext: (n: string) => `接頭辞「${n}」はこのサブジェクトの @context で属性名として使われています。別の接頭辞にしてください。`, duplicate: (n: string) => `「${n}」が 2 回あります。`,
      valueType: (n: string) => `「${n}」: 値の型を選んでください。`, format: (n: string) => `「${n}」: 書式が不正です。`, ngsiType: (n: string) => `「${n}」: NGSI-LD の型を選んでください。`,
    } as Record<string, any>,
  },
  en: {
    model: 'Model', prefix: 'Prefix', base: 'Namespace (your IRIs)', attributes: 'Your attributes', add: 'Add an attribute', remove: 'Remove',
