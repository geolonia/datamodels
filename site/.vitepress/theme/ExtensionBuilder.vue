const coreTerms = new Set<string>(data.coreTerms)
const modelId = ref(data.models.find((m: any) => m.id === 'transportation/RoadRestriction')?.id ?? data.models[0].id)
const model = computed(() => data.models.find((m: any) => m.id === modelId.value))
const form = reactive({
  prefix: 'acme', base: 'https://example.com/ns/acme/',
  attributes: [{ name: 'patrolRoute', ngsiType: 'Property', valueType: 'string', format: '', required: false, description: '' }] as any[],
})
onMounted(() => {
  const wanted = new URLSearchParams(location.search).get('model')
  if (wanted && data.models.some((m: any) => m.id === wanted)) modelId.value = wanted
})

const result = computed(() => buildExtension(model.value, form, coreTerms))
const messages = computed(() => result.value.problems.map((p) => { const m = L.problems[p.code]; return typeof m === 'function' ? m(p.name) : m }))
const pretty = (v: unknown) => JSON.stringify(v, null, 2)
const proposal = computed(() => proposalUrl(model.value, form.attributes))
const subjects = computed(() => [...new Set(data.models.map((m: any) => m.subject))].map((s) => ({ s, title: data.models.find((m: any) => m.subject === s).subjectTitle[props.lang], models: data.models.filter((m: any) => m.subject === s) })))

const add = () => form.attributes.push({ name: '', ngsiType: 'Property', valueType: 'string', format: '', required: false, description: '' })
const copied = ref('')
async function copy(which: 'context' | 'schema') {
  const text = pretty(which === 'context' ? result.value.context : result.value.schema)
  try { await navigator.clipboard.writeText(text); copied.value = which; setTimeout(() => (copied.value = ''), 1500) } catch { /* the text stays selectable */ }
}
</script>

